const CONSTELLATION_SOURCE = 'shared/authoring/constellations.toml'
const CONSTELLATION_OUTPUTS = [
  'shared/scenes/constellations.json',
  'web/lib/data/constellations.json',
  'native/LandnamCore/Sources/LandnamCore/Data/Constellations.generated.swift',
] as const

const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`

export function listDocs(root: string): { relPath: string; kind: DocKind }[] {
  const docs: { relPath: string; kind: DocKind }[] = []
  for (const dir of ['worlds', 'scenes', 'missions', 'flows', 'feedback', 'templates']) {
    const abs = join(root, AUTHORING_DIR, dir)
    if (!existsSync(abs)) continue
    for (const name of readdirSync(abs).sort()) {
      const relPath = `${AUTHORING_DIR}/${dir}/${name}`
      const kind = docKindOf(relPath)
      if (kind) docs.push({ relPath, kind })
    }
  }
  return docs
}

const MISSION_KEYS = ['id', 'title', 'brief', 'tag', 'template', 'difficulty', 'client', 'locked', 'sequence', 'unlock_at', 'target', 'delivery_target', 'harness'] as const

function missionDeclaration(value: MissionDoc): Record<string, unknown> {
  const out: Record<string, unknown> = {}
  for (const key of MISSION_KEYS) if (value[key] !== undefined) out[key] = value[key]
  const { requires, payout } = value
  out.requires = { minerals: requires.minerals, cargo_min: requires.cargo_min, drill_tier: requires.drill_tier, max_orbit: requires.max_orbit }
  out.payout = payout.floor_sequence !== undefined ? { floor_sequence: payout.floor_sequence, affinity: payout.affinity } : { francs: payout.francs, affinity: payout.affinity }
  return out
}

export function swiftMissionSource(jsonText: string): string {
  return [
    '// Generated by web/lib/authoring/compile.ts from shared/authoring/missions/*.toml. Do not edit.',
    '// After editing a mission run `npm run authoring:compile` (the Scene Studio does this when you save).',
    '',
    'enum AuthoredMissionDeclarations {',
    '    static let json = #"""',
    jsonText.trimEnd(),
    '"""#',
    '}',
    '',
  ].join('\n')
}

/**
 * Templates as the runtime reads them: forks resolved, so an event carries its parent's full beat list with its own
 * beats replacing same-id ones (new ids go before the last beat), and its parent's match tags never leak into it.
 */
export function resolveTemplates(docs: TemplateDoc[]): Record<string, unknown>[] {
  const byId = new Map(docs.map(d => [d.id, d]))
  return docs.map(doc => {
    let beats: TemplateBeat[] = doc.beat ?? []
    const parent = doc.fork_of ? byId.get(doc.fork_of) : undefined
    if (parent) {
      const own = new Map(beats.map(b => [b.id, b]))
      const merged = (parent.beat ?? []).map(b => own.get(b.id) ?? b)
      const added = beats.filter(b => !(parent.beat ?? []).some(p => p.id === b.id))
      if (added.length) merged.splice(Math.max(0, merged.length - 1), 0, ...added)
      beats = merged
    }
    const controls = [...new Set(beats.flatMap(b => b.controls))]
    const out: Record<string, unknown> = { id: doc.id, title: doc.title, family: doc.family }
    if (doc.fork_of) out.fork_of = doc.fork_of
    if (doc.window) out.window = doc.window
    out.summary = doc.summary
    out.vehicle = doc.vehicle
    if (doc.sources) out.sources = doc.sources
    out.match = { ids: doc.match?.ids ?? [], id_prefixes: doc.match?.id_prefixes ?? [], tags: doc.match?.tags ?? [] }
    out.beats = beats.map(b => ({ id: b.id, label: b.label, view: b.view, goal: b.goal, controls: b.controls, repeat: b.repeat ?? false }))
    out.controls = controls
    out.outcome = doc.outcome
    return out
  })
}

