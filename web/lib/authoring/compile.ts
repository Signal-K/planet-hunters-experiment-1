// TOML authoring sources to the runtime files that web and native load. One function serves the CLI, the drift test,
// CI and the Scene Studio's save, so what you see after saving is exactly what a build would produce.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { readSceneText, remapDiagnostics } from './fixtures-merge.ts'
import { AUTHORING_DIR, docKindOf, hasErrors, loadContext, scrapePresetKeys, validateDocument } from './validate.ts'
import type { AuthoringContext, DocKind, Diagnostic } from './validate.ts'
import type { MissionDoc, SceneDoc, WorldDoc } from './docs.ts'

export interface OutputFile {
  path: string
  content: string
}

export type FileStatus = 'current' | 'written' | 'stale'

export interface CompileResult {
  /** True when every document is free of errors and (in check mode) no output is stale. */
  ok: boolean
  diagnostics: Diagnostic[]
  files: { path: string; status: FileStatus; sources: string[] }[]
}

/** Worlds are named explicitly: a new world needs its output paths decided, not guessed. */
export const WORLD_OUTPUTS: Record<string, string[]> = {
  'base-world': ['shared/scenes/base-world.json', 'web/lib/world/base-world.json'],
}

export const MISSION_OUTPUTS = {
  json: 'shared/missions/authored-missions.json',
  web: 'web/lib/data/authored-missions.json',
  swift: 'native/LandnamCore/Sources/LandnamCore/Data/AuthoredMissions.generated.swift',
}

export const SCENE_OUTPUTS = {
  shared: 'shared/engine/authored-scenes.json',
  web: 'web/lib/engine/authored-scenes.json',
  swift: 'native/LandnamCore/Sources/LandnamCore/Scene/AuthoredScenes.generated.swift',
}

const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`

export function listDocs(root: string): { relPath: string; kind: DocKind }[] {
  const docs: { relPath: string; kind: DocKind }[] = []
  for (const dir of ['worlds', 'scenes', 'missions', 'flows', 'feedback']) {
    const abs = join(root, AUTHORING_DIR, dir)
    if (!existsSync(abs)) continue
    for (const name of readdirSync(abs).sort()) {
      const relPath = `${AUTHORING_DIR}/${dir}/${name}`
      const kind = docKindOf(relPath)
      if (kind) docs.push({ relPath, kind })
    }
  }
  return docs
}

const MISSION_KEYS = ['id', 'title', 'brief', 'tag', 'difficulty', 'client', 'locked', 'sequence', 'unlock_at', 'target', 'delivery_target', 'harness'] as const

function missionDeclaration(value: MissionDoc): Record<string, unknown> {
  const out: Record<string, unknown> = {}
  for (const key of MISSION_KEYS) if (value[key] !== undefined) out[key] = value[key]
  const { requires, payout } = value
  out.requires = { minerals: requires.minerals, cargo_min: requires.cargo_min, drill_tier: requires.drill_tier, max_orbit: requires.max_orbit }
  out.payout = payout.floor_sequence !== undefined ? { floor_sequence: payout.floor_sequence, affinity: payout.affinity } : { francs: payout.francs, affinity: payout.affinity }
  return out
}

export function swiftMissionSource(jsonText: string): string {
  return [
    '// Generated by web/lib/authoring/compile.ts from shared/authoring/missions/*.toml. Do not edit.',
    '// After editing a mission run `npm run authoring:compile` (the Scene Studio does this when you save).',
    '',
    'enum AuthoredMissionDeclarations {',
    '    static let json = #"""',
    jsonText.trimEnd(),
    '"""#',
    '}',
    '',
  ].join('\n')
}

export function swiftSceneSource(jsonText: string): string {
  return [
    '// Generated by web/lib/authoring/compile.ts from shared/authoring/scenes/*.toml. Do not edit.',
    '// This is the same scene graph consumed by the web engine adapter.',
    '',
    'enum AuthoredSceneDeclarations {',
    '    static let json = #"""',
    jsonText.trimEnd(),
    '"""#',
    '}',
    '',
  ].join('\n')
}

function sceneDeclaration(value: SceneDoc): Record<string, unknown> {
  return {
    id: value.id,
    type: value.type,
    route: value.preview.route,
    surface: value.runtime.surface,
    runtime: value.runtime,
    objects: value.objects ?? [],
  }
}

export interface CompileOptions {
  root: string
  write: boolean
  presets?: ReadonlySet<string>
  /** Text to use instead of what is on disk, keyed by repo-relative path. Lets the Studio validate before saving. */
  overlay?: Record<string, string>
}

export function compileAll(options: CompileOptions): CompileResult {
  const { root, write, overlay = {} } = options
  const context: AuthoringContext = loadContext(root, options.presets ?? scrapePresetKeys(root))
  const diagnostics: Diagnostic[] = [...(context.contractDiagnostics ?? [])]
  const valid = new Map<string, unknown>()
  const readText = (relPath: string) => readSceneText(root, relPath, overlay)

  for (const { relPath } of listDocs(root)) {
    const text = readText(relPath)
    const result = validateDocument(text, relPath, context)
    diagnostics.push(...remapDiagnostics(text, result.diagnostics))
    if (result.doc && !hasErrors(result.diagnostics)) valid.set(relPath, result.doc.value)
  }

  const outputs: (OutputFile & { sources: string[] })[] = []

  for (const [name, paths] of Object.entries(WORLD_OUTPUTS)) {
    const source = `${AUTHORING_DIR}/worlds/${name}.toml`
    const value = valid.get(source)
    if (!value) continue
    const { format: _format, ...runtime } = value as WorldDoc
    for (const path of paths) outputs.push({ path, content: json(runtime), sources: [source] })
  }

  const missionSources = listDocs(root).filter(d => d.kind === 'mission').map(d => d.relPath)
  if (missionSources.length && missionSources.every(s => valid.has(s))) {
    const seen = new Map<string, string>()
    let unique = true
    for (const source of missionSources) {
      const id = (valid.get(source) as MissionDoc).id
      if (seen.has(id)) {
        unique = false
        diagnostics.push({ file: source, severity: 'error', code: 'duplicate-id', message: `mission id "${id}" is already defined in ${seen.get(id)}`, line: 1, column: 1, endLine: 1, endColumn: 1 })
      } else seen.set(id, source)
    }
    if (unique) {
      const text = json({ version: 1, missions: missionSources.map(s => missionDeclaration(valid.get(s) as MissionDoc)) })
      outputs.push(
        { path: MISSION_OUTPUTS.json, content: text, sources: missionSources },
        { path: MISSION_OUTPUTS.web, content: text, sources: missionSources },
        { path: MISSION_OUTPUTS.swift, content: swiftMissionSource(text), sources: missionSources },
      )
    }
  }

  const sceneSources = listDocs(root).filter(d => d.kind === 'scene').map(d => d.relPath)
  if (sceneSources.length && sceneSources.every(s => valid.has(s))) {
    const text = json({
      version: 1,
      coordinateSpace: context.sceneTypes.coordinateSpace ?? 'normalized-safe-area',
      journey: context.sceneTypes.journey,
      slots: context.sceneTypes.sharedSlots,
      mechanics: context.mechanics ?? [],
      scenes: sceneSources.map(source => sceneDeclaration(valid.get(source) as SceneDoc)),
    })
    outputs.push(
      { path: SCENE_OUTPUTS.shared, content: text, sources: sceneSources },
      { path: SCENE_OUTPUTS.web, content: text, sources: sceneSources },
      { path: SCENE_OUTPUTS.swift, content: swiftSceneSource(text), sources: sceneSources },
    )
  }

  const files: CompileResult['files'] = []
  // A bad scene must never leave web, Swift and the mission/world data on different revisions.
  if (hasErrors(diagnostics)) return { ok: false, diagnostics, files }
  for (const output of outputs) {
    const abs = join(root, output.path)
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null
    if (current === output.content) {
      files.push({ path: output.path, status: 'current', sources: output.sources })
    } else if (write) {
      mkdirSync(dirname(abs), { recursive: true })
      writeFileSync(abs, output.content)
      files.push({ path: output.path, status: 'written', sources: output.sources })
    } else {
      files.push({ path: output.path, status: 'stale', sources: output.sources })
    }
  }

  const ok = !hasErrors(diagnostics) && files.every(f => f.status !== 'stale')
  return { ok, diagnostics, files }
}
