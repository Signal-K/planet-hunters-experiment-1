import { useEffect, useRef, useState } from 'react'
import * as engine from '@takeon/engine'
import { buildLandnamBody } from '@landnam/lib/takeon/sandbox'
import { takeonBodyForTarget } from '@landnam/lib/takeon/bodies'
import type { Target } from '@landnam/lib/data/types'
import { MINERAL_META } from '@landnam/lib/data/minerals'
import type { Base, StructureState } from './structures'

export interface Deposit {
  key: number
  mineral: string
  col: number
  row: number
  cut: boolean
  locked: boolean
}
type FieldProps = {
  children?: React.ReactNode
  navigation?: React.ReactNode
  readout?: string
  notice?: string | null
  cargo?: React.ReactNode
  onAbort?: () => void
  onPlace?: () => void
  base: Base
  pilotId?: string
  target?: Target
  phase?: string
  deposits?: Deposit[]
  onCut?: (key: number) => void
  inspect?: (s: StructureState) => void
  onWork?: () => void
  onDepart?: () => void
  done?: boolean
  busy?: boolean
  survey?: boolean
  siteLabel?: string
  departureGoal?: string
  workLabel?: string
  event?: boolean
  payload?: string
  raising?: number
  crates?: boolean
  beam?: number
  objective?: string
}
type Tile = engine.Vec2
type Landmark = { id: string; pos: Tile; kind: string }
const kit = '/game/assets/base/kit/'
const decor: Record<string, string> = {
  pine: new URL('./art/props/pine.png', import.meta.url).href,
  rock: kit + 'prop-rock.png',
  pylon: kit + 'pylon.png',
  tank: kit + 'water-tower.png',
}
const order = ['hangar', 'launchpad', 'control-station', 'exchange']
const sites = [
  [-4, 1],
  [0, -3],
  [4, 1],
  [0, 4],
]
const fieldSites = [
  [2, -1],
  [-3, 1],
  [1, 3],
  [3, 2],
  [-1, -3],
  [-2, 3],
  [-4, 0],
  [3, -3],
  [2, 4],
  [-3, -3],
  [4, 0],
  [-1, 4],
]
function load<T>(key: string, fallback: T): T {
  try {
    return JSON.parse(localStorage.getItem(key) || 'null') ?? fallback
  } catch {
    return fallback
  }
}
const distance = (a: Tile, b: Tile) => Math.abs(a.x - b.x) + Math.abs(a.y - b.y)
const clamp = (v: number, min: number, max: number) => Math.max(min, Math.min(max, v))
const textures = new Map<string, HTMLImageElement>()
function drawImage(ctx: CanvasRenderingContext2D, src: string, x: number, y: number, w: number, h: number) {
  let img = textures.get(src)
  if (!img) {
    img = new Image()
    img.src = src
    textures.set(src, img)
  }
  if (img.complete && img.naturalWidth) ctx.drawImage(img, x - w / 2, y - h, w, h)
}
export function World(props: FieldProps) {
  const canvas = useRef<HTMLCanvasElement>(null),
    overlay = useRef<HTMLCanvasElement>(null),
    live = useRef(props)
  live.current = props
  const [editing, setEditing] = useState(false),
    [tool, setTool] = useState('launchpad'),
    [hint, say] = useState(''),
    [surveyed, setSurveyed] = useState(0)
  const [landing, setLanding] = useState<'descent' | 'ready' | 'driving'>(props.target ? 'descent' : 'driving')
  const deploy = useRef(() => {})
  const editor = useRef({ editing, tool })
  editor.current = { editing, tool }
  const key = 'landnam-minimal:takeon-base:' + props.pilotId
  const ops = useRef({ move: (_dir: 0 | 1 | 2 | 3) => {}, activate: () => {}, undo: () => {}, centre: () => {} })
  useEffect(() => {
    const el = canvas.current!,
      ink = overlay.current!,
      ctx = ink.getContext('2d')!
    const target = props.target,
      home = !target
    const arrival = !home && props.phase === 'away'
    const descentTime = window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 0 : 2.6
    let driving = !arrival
    setLanding(arrival ? 'descent' : 'driving')
    const landed = arrival ? window.setTimeout(() => setLanding('ready'), descentTime * 1000) : undefined
    const raw = home
      ? engine.cloneBody(engine.getBody('terra')!)
      : buildLandnamBody(engine, takeonBodyForTarget(target), target)
    // Keep a contiguous landing zone for the rover. The relief beyond it is generated by TakeOn.
    raw.size = 48
    raw.dayLength = 0
    if (home) {
      raw.palette.tint = [0.66, 0.68, 0.79]
      raw.terrain.iceCaps = 0
    }
    const game = engine.createRoverGame({
      canvas: el,
      body: raw,
      spec: engine.defaultSpec(),
      controls: false,
      audio: false,
      showRover: false,
      startView: 'iso',
    })
    const sim = game.sim,
      world = sim.world,
      spawn = { ...sim.rover.pos }
    const grade = world.height(spawn.x, spawn.y)
    const surface = home
      ? engine.Material.Grass
      : world.surfaceMaterial(spawn.x, spawn.y) || engine.Material.Regolith
    for (let i = -6; i <= 6; i++)
      for (let j = -6; j <= 6; j++) {
        const x = spawn.x + i,
          y = spawn.y + j
        if (!world.inBounds(x, y)) continue
        const z = world.height(x, y)
        for (let k = z; k > grade; k--) world.set(x, y, k, engine.Material.Air)
        for (let k = Math.max(0, z); k <= grade; k++) world.set(x, y, k, surface)
        if (home && (i === 0 || j === 1)) world.set(x, y, grade, engine.Material.Rock)
      }
    game.camera.follow = false
    function centre() {
      game.camera.follow = false
      game.iso.focusTile(spawn)
    }
    function resize() {
      const w = el.clientWidth,
        h = el.clientHeight,
        d = Math.min(1.5, devicePixelRatio || 1)
      game.resize(w, h, d)
      ink.width = w * d
      ink.height = h * d
      ctx.setTransform(d, 0, 0, d, 0, 0)
      game.camera.minZoom = 0.7
      game.camera.maxZoom = 4
      game.camera.zoom = clamp(Math.min(w / 230, h / 215), 1, 2.6)
      centre()
    }
    const at = (offset: number[]) => ({ x: spawn.x + offset[0], y: spawn.y + offset[1] })
    const previous = load<string[]>('landnam-minimal:positions:' + props.pilotId, order)
    const defaults = (previous.length === 4 && order.every((id) => previous.includes(id)) ? previous : order).map(
      (id, i) => ({ id, kind: id, pos: at(sites[i]) }),
    )
    const legacy = load<{ id: string; kind: string; x: number; y: number }[]>(
      'landnam-minimal:props:' + props.pilotId,
      [],
    )
    const scenery: Landmark[] = []
    for (let i = -12; i <= 12; i++)
      for (let j = -12; j <= 12; j++) {
        const rim = Math.max(Math.abs(i), Math.abs(j))
        const n = ((Math.imul(i + 16, 73856093) ^ Math.imul(j + 16, 19349663)) >>> 0) % 101
        if (rim < 5 || n > (rim > 6 ? 28 : 14) || !world.isSolid(spawn.x + i, spawn.y + j)) continue
        scenery.push({ id: 'grove-' + i + '-' + j, kind: n % 7 === 0 ? 'rock' : 'pine', pos: at([i, j]) })
      }
    for (const [i, j, k] of [
      [-2, -3, 'pylon'],
      [-3, -4, 'pylon'],
      [5, 3, 'tank'],
      [-3, 3, 'rock'],
    ] as const)
      scenery.push({ id: 'prop-' + i + '-' + j, kind: k, pos: at([i, j]) })
    const landmarks = home
      ? load<Landmark[]>(key, [
          ...scenery,
          ...defaults,
          ...legacy
            .filter((p) => decor[p.kind])
            .map((p) => ({
              id: p.id,
              kind: p.kind,
              pos: at([Math.round(p.x / 100) - 4, Math.round((p.y - 214) / 25) + 2]),
            })),
        ])
      : []
    const save = () => {
      if (props.pilotId) localStorage.setItem(key, JSON.stringify(landmarks))
    }
    const seen = new Set<number>()
    setSurveyed(0)
    say('')
    let pending: { pos: Tile; action: () => void } | null = null
    let pulse: { pos: Tile; start: number } | null = null
    const clickables: { x: number; y: number; r: number; halfWidth?: number; act: () => void; pos: Tile }[] = []
    function approach(pos: Tile, action: () => void) {
      const current = sim.rover.pos
      if (distance(current, pos) <= 1) {
        game.cancelOrder()
        pending = null
        action()
        return
      }
      const adjacent = [
        { x: pos.x + 1, y: pos.y },
        { x: pos.x - 1, y: pos.y },
        { x: pos.x, y: pos.y + 1 },
        { x: pos.x, y: pos.y - 1 },
      ].sort((a, b) => distance(a, current) - distance(b, current))
      for (const t of adjacent) {
        if (world.isSolid(t.x, t.y) && game.planPath([t])) {
          pending = { pos, action }
          say('Rover en route')
          return
        }
      }
      say('Route blocked · approach from another side')
    }
    const screen = (pos: Tile) => {
      const v = game.iso.toView(pos.x, pos.y),
        p = engine.project(v.x, v.y, game.iso.surfaceZ(Math.round(pos.x), Math.round(pos.y)))
      return game.camera.toScreen(p.sx, p.sy)
    }
    deploy.current = () => {
      driving = true
      setLanding('driving')
      game.walkTo(spawn.x + 1, spawn.y)
    }
    const menuOpen = () => !driving || !!document.querySelector('dialog[open],.op-desk')
    let drag: { x: number; y: number; moved: boolean; startX: number; startY: number } | null = null
    const down = (e: PointerEvent) => {
      if (menuOpen()) return
      el.focus({ preventScroll: true })
      el.setPointerCapture(e.pointerId)
      drag = { x: e.clientX, y: e.clientY, moved: false, startX: e.clientX, startY: e.clientY }
    }
    const move = (e: PointerEvent) => {
      if (!drag) return
      if (Math.hypot(e.clientX - drag.startX, e.clientY - drag.startY) > 5) drag.moved = true
      if (drag.moved) game.camera.panBy(e.clientX - drag.x, e.clientY - drag.y)
      drag.x = e.clientX
      drag.y = e.clientY
    }
    const up = (e: PointerEvent) => {
      if (!drag) return
      const tap = !drag.moved
      drag = null
      if (!tap || menuOpen()) return
      const b = el.getBoundingClientRect(),
        x = e.clientX - b.left,
        y = e.clientY - b.top,
        tile = game.iso.pickTile(x, y)
      if (editor.current.editing && home && tile) {
        if (!world.isSolid(tile.x, tile.y) || landmarks.some((l) => distance(l.pos, tile) === 0)) {
          say('Choose an open tile')
          return
        }
        const kind = editor.current.tool
        const existing = landmarks.find((l) => l.id === kind)
        if (existing) existing.pos = tile
        else landmarks.push({ id: crypto.randomUUID(), kind, pos: tile })
        save()
        say('Placed')
        return
      }
      const hit = clickables
        .slice()
        .reverse()
        .find(
          (c) =>
            Math.hypot(c.x - x, c.y - y) < c.r ||
            (c.halfWidth !== undefined && Math.abs(x - c.x) <= c.halfWidth && Math.abs(y - c.y) < 16),
        )
      if (hit) {
        hit.act()
        return
      }
      if (tile) {
        pending = null
        game.walkTo(tile.x, tile.y)
        say('')
      }
    }
    const wheel = (e: WheelEvent) => {
      e.preventDefault()
      const b = el.getBoundingClientRect()
      game.camera.setZoom(game.camera.zoom * Math.exp(-e.deltaY * 0.001), e.clientX - b.left, e.clientY - b.top)
    }
    ops.current = {
      centre,
      move: (dir) => {
        pending = null
        game.move(dir)
      },
      activate: () => {
        const h = clickables
          .slice()
          .sort((a, b) => distance(a.pos, sim.rover.pos) - distance(b.pos, sim.rover.pos))[0]
        h?.act()
      },
      undo: () => {
        const i = landmarks
          .map((l) => !!decor[l.kind] && !l.id.startsWith('grove-') && !l.id.startsWith('prop-'))
          .lastIndexOf(true)
        if (i >= 0) {
          landmarks.splice(i, 1)
          save()
        }
      },
    }
    const keyboard = (e: KeyboardEvent) => {
      if (menuOpen() || e.target instanceof HTMLSelectElement) return
      const i = ['ArrowRight', 'ArrowDown', 'ArrowLeft', 'ArrowUp'].indexOf(e.key),
        j = ['d', 's', 'a', 'w'].indexOf(e.key.toLowerCase())
      if (i >= 0 || j >= 0) {
        e.preventDefault()
        ops.current.move((i >= 0 ? i : j) as 0 | 1 | 2 | 3)
      }
      if ((e.key === 'Enter' || e.key === ' ') && e.target === el) {
        e.preventDefault()
        ops.current.activate()
      }
    }
    el.addEventListener('pointerdown', down)
    el.addEventListener('pointermove', move)
    el.addEventListener('pointerup', up)
    const cancel = () => {
      drag = null
    }
    el.addEventListener('pointercancel', cancel)
    el.addEventListener('wheel', wheel, { passive: false })
    window.addEventListener('keydown', keyboard)
    const ro = new ResizeObserver(resize)
    ro.observe(el)
    resize()
    game.start()
    let frame = 0
    const epoch = performance.now()
    function render(now: number) {
      const p = live.current,
        zoom = game.camera.zoom,
        t = Math.max(0, (now - epoch) / 1000)
      ctx.clearRect(0, 0, el.clientWidth, el.clientHeight)
      clickables.length = 0
      if (pending && distance(pending.pos, sim.rover.pos) <= 1) {
        const job = pending
        pending = null
        game.cancelOrder()
        say('')
        job.action()
      }
      function flag(pos: Tile, label: string, act: () => void, color = '#ffe2a5', lift = 0) {
        const pt = screen(pos),
          y = pt.y - lift,
          r = Math.max(20, zoom * 7)
        ctx.strokeStyle = color
        ctx.lineWidth = 2
        ctx.beginPath()
        ctx.ellipse(pt.x, pt.y, 13 * zoom, 6 * zoom, 0, 0, Math.PI * 2)
        ctx.stroke()
        if (label) {
          ctx.font = '600 13px system-ui'
          ctx.textAlign = 'center'
          const width = ctx.measureText(label).width + 18
          ctx.fillStyle = '#111e29e8'
          ctx.fillRect(pt.x - width / 2, y - 26, width, 22)
          ctx.fillStyle = color
          ctx.fillText(label, pt.x, y - 11)
        }
        clickables.push({ x: pt.x, y: pt.y - lift / 2, r: Math.max(16, lift / 2), act, pos })
        clickables.push({
          x: pt.x,
          y: y - 10,
          r,
          halfWidth: label ? ctx.measureText(label).width / 2 + 9 : undefined,
          act,
          pos,
        })
      }
      const roverTile = sim.rover.renderPos
      const drawVehicle = () => {
        const pt = screen(roverTile)
        engine.drawRover(ctx, pt.x, pt.y, zoom * 0.27, sim.rover, sim.daylight(), sim.rover.facing, t)
      }
      if (home) {
        for (const l of [...landmarks, { id: 'rover', kind: 'rover', pos: roverTile }].sort(
          (a, b) => a.pos.x + a.pos.y - b.pos.x - b.pos.y,
        )) {
          const pt = screen(l.pos),
            s = p.base.structures.find((s) => s.def.id === l.kind)
          if (l.kind === 'rover') {
            drawVehicle()
            continue
          }
          if (!s) {
            const tree = l.kind === 'pine'
            const size = tree ? 19 + ((l.pos.x * 3 + l.pos.y * 7) % 11) : l.kind === 'rock' ? 11 : 20
            if (tree) {
              ctx.fillStyle = '#152b284d'
              ctx.beginPath()
              ctx.ellipse(pt.x + 4 * zoom, pt.y, size * zoom * 0.47, 3 * zoom, -0.18, 0, Math.PI * 2)
              ctx.fill()
            }
            if (pt.x > -100 && pt.x < el.clientWidth + 100 && pt.y > -40 && pt.y < el.clientHeight + 110)
              drawImage(ctx, decor[l.kind], pt.x, pt.y, size * zoom, (tree ? size * 1.36 : size) * zoom)
            continue
          }
          const pad = l.id === 'launchpad',
            w = (pad ? 52 : 44) * zoom,
            h = (pad ? 45 : 28) * zoom
          drawImage(ctx, s.def.art[s.level - 1], pt.x, pt.y, w, h)
          if (pad) {
            const lift =
              p.phase === 'launch'
                ? t * t * el.clientHeight
                : p.phase === 'land'
                  ? Math.max(0, 1 - t / 1.5) ** 2 * el.clientHeight
                  : 0
            drawImage(ctx, kit + 'pad-rocket.png', pt.x + 2 * zoom, pt.y - 5 * zoom - lift, 13 * zoom, 37 * zoom)
          }
          const activate = () => p.inspect?.(s)
          if (!p.phase) {
            flag(l.pos, pad ? p.objective || 'Launch' : s.def.name, activate, pad ? '#ffbd65' : '#c0ebd4', h)
            clickables.push({ x: pt.x, y: pt.y - h * 0.45, r: Math.max(22, w * 0.43), act: activate, pos: l.pos })
          }
        }
      } else {
        const remaining = arrival && descentTime ? Math.max(0, 1 - t / descentTime) : 0
        const lift =
          p.phase === 'leaving' ? t * t * el.clientHeight : remaining * remaining * el.clientHeight * 0.82
        if (arrival && !driving) {
          game.iso.focusTile(spawn)
          game.camera.cy -= (lift * 0.38) / zoom
        }
        const berth = screen(spawn)
        if (p.target?.id === 'moon') {
          for (const [i, j, size] of [
            [-4, -2, 9],
            [1, -4, 6],
            [-2, 2, 4],
            [4, 3, 11],
            [-3, 4, 7],
            [4, -2, 6],
          ]) {
            const rock = screen(at([i, j]))
            drawImage(
              ctx,
              '/game/assets/terrain/rock_cluster.png',
              rock.x,
              rock.y,
              size * zoom,
              size * 0.64 * zoom,
            )
          }
        }
        const x = berth.x + remaining * el.clientWidth * 0.18,
          y = berth.y - lift
        ctx.fillStyle = 'rgba(8,16,22,' + 0.28 * (1 - remaining) + ')'
        ctx.beginPath()
        ctx.ellipse(berth.x, berth.y, (10 + remaining * 6) * zoom, 4 * zoom, 0, 0, Math.PI * 2)
        ctx.fill()
        if (remaining > 0 || p.phase === 'leaving')
          drawImage(ctx, kit + 'flame-' + (Math.floor(t * 14) % 3) + '.png', x, y + 12 * zoom, 8 * zoom, 15 * zoom)
        drawImage(ctx, kit + 'space-rocket.png', x, y, 15 * zoom, 40 * zoom)
        if (arrival && descentTime && t > descentTime - 0.65 && t < descentTime + 0.6) {
          const dust = (t - descentTime + 0.65) / 1.25
          ctx.save()
          ctx.globalAlpha = 0.65 * (1 - dust)
          for (let i = 0; i < 8; i++) {
            const angle = (i * Math.PI) / 4
            drawImage(
              ctx,
              kit + 'pad-smoke-' + (i % 4) + '.png',
              berth.x + Math.cos(angle) * dust * 32 * zoom,
              berth.y + Math.sin(angle) * dust * 7 * zoom,
              15 * zoom,
              9 * zoom,
            )
          }
          ctx.restore()
        }
        if (!driving || p.phase === 'leaving') {
          frame = requestAnimationFrame(render)
          return
        }
        drawVehicle()
        if (p.done) {
          flag(
            spawn,
            'Return to ship',
            () => approach(spawn, () => live.current.onDepart?.()),
            '#ffbd65',
            36 * zoom,
          )
        } else if (p.deposits?.length) {
          const active = p.deposits.filter((d) => !d.cut)
          active.forEach((d) => {
            const pos = at(
              fieldSites[(d.row * Math.max(3, ...p.deposits!.map((x) => x.col + 1)) + d.col) % fieldSites.length],
            )
            const pt = screen(pos),
              meta = MINERAL_META[d.mineral]
            const oreArt = ['iron', 'nickel', 'gold', 'ice', 'cobalt', 'carbon', 'silicon'].includes(d.mineral)
              ? d.mineral
              : 'rare'
            const fragment = d.mineral.endsWith('_debris')
            const art = fragment
              ? '/game/assets/events/orionids/debris/debris-0' + ((d.key % 4) + 1) + '.png'
              : '/game/assets/ores/ore_' + oreArt + '.png'
            drawImage(ctx, art, pt.x, pt.y, 18 * zoom, 16 * zoom)
            if (fragment) {
              const approach = Math.max(0, 1 - ((t + d.key * 0.67) % 4))
              if (approach > 0)
                drawImage(
                  ctx,
                  '/game/assets/events/orionids/fx/streak-01.png',
                  pt.x - approach * 70 * zoom,
                  pt.y - approach * 90 * zoom,
                  19 * zoom,
                  28 * zoom,
                )
            }
            flag(
              pos,
              meta?.sym || '✦',
              () =>
                approach(pos, () => {
                  pulse = { pos, start: performance.now() }
                  if (!d.locked && !p.event && world.height(pos.x, pos.y) >= grade) world.mineTop(pos.x, pos.y)
                  live.current.onCut?.(d.key)
                }),
              meta?.color || '#ffe2a5',
              8 * zoom,
            )
          })
        } else if (!p.busy) {
          const count = p.survey ? 3 : 1
          for (let i = 0; i < count; i++) {
            const pos = at(fieldSites[i])
            const pt = screen(pos)
            drawImage(ctx, '/game/assets/terrain/far_mast.png', pt.x, pt.y, 9 * zoom, 17 * zoom)
            if (seen.has(i)) continue
            flag(
              pos,
              p.survey ? '⌖ ' + (i + 1) : p.siteLabel || 'Deploy',
              () =>
                approach(pos, () => {
                  if (seen.has(i)) return
                  seen.add(i)
                  pulse = { pos, start: performance.now() }
                  game.scan()
                  setSurveyed(seen.size)
                  if (seen.size === count) live.current.onWork?.()
                }),
              '#9ff9e3',
              17 * zoom,
            )
          }
        }
        if (p.payload) {
          const pos = at(fieldSites[p.survey ? 2 : 0])
          drawImage(ctx, kit + 'pylon.png', screen(pos).x, screen(pos).y, 17 * zoom, 24 * zoom)
        }
        if (p.crates || p.raising !== undefined) {
          const pos = screen(at(fieldSites[0]))
          drawImage(ctx, kit + 'starter-cabin.png', pos.x, pos.y, 26 * zoom, 18 * zoom * (p.raising ?? 1))
        }
      }
      if (pulse) {
        const age = (now - pulse.start) / 900
        if (age < 1) {
          const pt = screen(pulse.pos)
          ctx.strokeStyle = 'rgba(129,255,219,' + (1 - age) + ')'
          ctx.lineWidth = 3
          ctx.beginPath()
          ctx.ellipse(pt.x, pt.y, Math.max(1, age * 80 * zoom), Math.max(1, age * 36 * zoom), 0, 0, Math.PI * 2)
          ctx.stroke()
        } else pulse = null
      }
      frame = requestAnimationFrame(render)
    }
    frame = requestAnimationFrame(render)
    return () => {
      window.clearTimeout(landed)
      cancelAnimationFrame(frame)
      ro.disconnect()
      el.removeEventListener('pointerdown', down)
      el.removeEventListener('pointermove', move)
      el.removeEventListener('pointerup', up)
      el.removeEventListener('pointercancel', cancel)
      el.removeEventListener('wheel', wheel)
      window.removeEventListener('keydown', keyboard)
      game.dispose()
    }
  }, [props.target?.id, props.pilotId, props.phase, key])
  const aircraft = props.target ? 'Rover operations' : 'Agency operations'
  const underway = props.phase === 'launch' || props.phase === 'land' || props.phase === 'leaving'
  const activity =
    props.phase === 'launch'
      ? 'Liftoff'
      : props.phase === 'land'
        ? 'Homecoming'
        : props.phase === 'leaving'
          ? 'Departing'
          : editing
            ? 'Site planning'
            : props.target
              ? landing === 'driving'
                ? 'Surface operations'
                : 'Landing sequence'
              : aircraft
  return (
    <section className="play-shell" aria-label="Landnam flight deck">
      <div className="world-window">
        <div data-body={props.target?.id} className={'takeon-field' + (props.target ? '' : ' earth-field')}>
          <canvas
            ref={canvas}
            tabIndex={0}
            aria-label="TakeOn terrain. Tap to drive, use arrow keys to steer, and press Space to interact."
          />
          <canvas ref={overlay} aria-hidden="true" className="terrain-objects" />
        </div>
      </div>
      <section data-editing={editing} className="cockpit" aria-label="Flight controls">
        <header className="deck-header">
          <div className="deck-location">
            <span className="deck-roundel" aria-hidden>
              ◈
            </span>
            <strong>{props.target?.name || 'Earth station'}</strong>
            <span className="deck-phase">{activity}</span>
          </div>
          <span className="deck-account">{props.readout}</span>
        </header>
        <div className="deck-body">
          {editing ? (
            <section className="deck-placement">
              <small>GROUND CREW</small>
              <h2>Place an object</h2>
              <p>Choose an object, then select an open tile in the terrain.</p>
              <div>
                <select aria-label="Object to place" value={tool} onChange={(e) => setTool(e.target.value)}>
                  {[...order, ...Object.keys(decor)].map((id) => (
                    <option key={id}>{id}</option>
                  ))}
                </select>
                <button onClick={() => ops.current.undo()}>Undo prop</button>
              </div>
            </section>
          ) : (
            props.children
          )}
          {props.target &&
            !underway &&
            (landing === 'driving' ? (
              <section className="rover-job">
                <small>ROVER TELEMETRY</small>
                <h2>
                  {props.done
                    ? 'Ready for departure'
                    : props.survey
                      ? 'Survey the landing zone'
                      : props.deposits
                        ? 'Recover cargo'
                        : props.siteLabel}
                </h2>
                <p className="field-job" role="status">
                  {props.done
                    ? props.departureGoal
                    : props.survey
                      ? surveyed === 3
                        ? 'Transmitting survey…'
                        : 'Tap a numbered beacon to scan · ' + surveyed + ' / 3'
                      : props.workLabel}
                </p>
                {props.survey && (
                  <div className="beacon-strip" aria-label={surveyed + ' of 3 sites scanned'}>
                    {[0, 1, 2].map((i) => (
                      <i key={i} className={surveyed > i ? 'lit' : ''} />
                    ))}
                  </div>
                )}
                {props.cargo}
                <div className="rover-controls">
                  <div className="steering" role="group" aria-label="Steer rover">
                    {(['East', 'South', 'West', 'North'] as const).map((dir, i) => (
                      <button
                        key={dir}
                        data-dir={dir}
                        aria-label={'Drive ' + dir.toLowerCase()}
                        onClick={() => ops.current.move(i as 0 | 1 | 2 | 3)}
                      >
                        <i />
                      </button>
                    ))}
                  </div>
                  {(props.done || !props.deposits?.length) && (
                    <button
                      className="story-go"
                      disabled={!!props.busy && !props.done}
                      onClick={() => ops.current.activate()}
                    >
                      {props.done ? 'Board ship' : props.survey ? 'Drive to next beacon' : 'Drive to work site'}
                    </button>
                  )}
                </div>
              </section>
            ) : (
              <div className="touchdown-radio" aria-live="polite">
                <small>LANDER · {props.target.name}</small>
                <h2>{landing === 'descent' ? 'Final approach' : 'Touchdown confirmed'}</h2>
                {landing === 'descent' ? (
                  <p>Retrorockets firing. Stand by for rover release.</p>
                ) : (
                  <>
                    <p>
                      {props.survey
                        ? 'Send the rover to each of the three survey beacons, then return to the ship.'
                        : props.workLabel + '. Return to the ship when the job is complete.'}
                    </p>
                    <button className="story-go" onClick={() => deploy.current()}>
                      Deploy rover ▸
                    </button>
                  </>
                )}
              </div>
            ))}
          {underway && (
            <section className="rover-job">
              <small>FLIGHT DIRECTOR</small>
              <h2>{activity}</h2>
              <p>{props.objective || 'On course for the next landing.'}</p>
            </section>
          )}
          {(props.notice || hint) && (
            <p className="deck-notice" role="status">
              {props.notice || hint}
            </p>
          )}
        </div>
        <div className="deck-controls">
          {props.navigation && (
            <nav
              aria-label="Station instruments"
              onClickCapture={() => {
                setEditing(false)
                say('')
              }}
            >
              {props.navigation}
            </nav>
          )}
          {props.pilotId && !props.target && !props.phase && (
            <button
              aria-pressed={editing}
              onClick={() => {
                props.onPlace?.()
                setEditing(!editing)
                say('')
              }}
            >
              {editing ? 'Finish placing' : 'Place'}
            </button>
          )}
          <button
            className="deck-camera"
            aria-label="Centre camera"
            title="Centre camera"
            onClick={() => ops.current.centre()}
          >
            ⌖ <span>Centre</span>
          </button>
          {props.onAbort && (
            <button className="deck-abort" onClick={props.onAbort}>
              Abort flight
            </button>
          )}
        </div>
      </section>
    </section>
  )
}
