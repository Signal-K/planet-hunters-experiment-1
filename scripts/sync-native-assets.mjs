#!/usr/bin/env node

import { createHash } from "node:crypto";
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import process from "node:process";

const root = resolve(import.meta.dirname, "..");
const manifestPath = resolve(root, "web/public/game/assets/manifest.json");
const webAssets = resolve(root, "web/public/game/assets");
const nativeAssets = resolve(root, "native/App/Resources/Art");
const reports = [resolve(root, "docs/native-asset-sync-triage.md"), "/Users/scroobz/Navigation/orbit-review/asset-diff.md"];
const check = process.argv.includes("--check");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const sha = async (file) => createHash("sha256").update(await readFile(file)).digest("hex").slice(0, 12);
const entries = [];

for (const [key, url] of Object.entries(manifest)) {
  if (!url.startsWith("/game/assets/") || !url.endsWith(".png")) continue;
  const path = url.slice("/game/assets/".length);
  const web = resolve(webAssets, path);
  const native = resolve(nativeAssets, path);
  try { await stat(web); } catch { entries.push({ key, path, state: "manifest-missing-source" }); continue; }
  try {
    await stat(native);
    entries.push({ key, path, state: (await sha(web)) === (await sha(native)) ? "identical" : "different" });
  } catch {
    // New art can affect composition and is intentionally never copied without an explicit reviewed allow-list.
    entries.push({ key, path, state: "missing" });
  }
}

const grouped = (state) => entries.filter((entry) => entry.state === state);
const section = (title, items) => `## ${title} (${items.length})\n\n${items.length ? items.map(({ key, path }) => `- \`${key}\` — \`${path}\``).join("\n") : "None."}\n`;
const report = `# Native asset sync triage\n\nGenerated by \`scripts/sync-native-assets.mjs\` from \`web/public/game/assets/manifest.json\`. This report is deliberately a review list: it does not overwrite differing native art or copy missing art until a reviewed allow-list exists.\n\n- **Keep candidates** have a native path with a different SHA-256 prefix. Preserve the native composition unless a visual owner explicitly approves replacement.\n- **Replace candidates** are present in web but absent in the native Art bundle. They need an import/layout review before copying; no files were added by this Stage 1 script.\n- **Synced** files already have byte-identical content.\n\n${section("Synced", grouped("identical"))}\n${section("Keep candidates: existing native art differs", grouped("different"))}\n${section("Replace candidates: missing from native Art", grouped("missing"))}\n${section("Manifest paths missing a web source", grouped("manifest-missing-source"))}`;

let stale = false;
for (const output of reports) {
  let current = "";
  try { current = await readFile(output, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (current === report) continue;
  stale = true;
  if (check) { console.error(`Out of sync: ${output}`); continue; }
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, report);
  console.log(`Updated ${relative(root, output) || output}`);
}
if (stale && check) process.exitCode = 1;
