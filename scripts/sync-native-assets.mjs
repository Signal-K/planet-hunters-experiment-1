#!/usr/bin/env node

import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import process from "node:process";

const root = resolve(import.meta.dirname, "..");
const manifestPath = resolve(root, "web/public/game/assets/manifest.json");
const webAssets = resolve(root, "web/public/game/assets");
const nativeAssets = resolve(root, "native/App/Resources/Art");
const reportPath = resolve(root, "docs/native-asset-sync-triage.md");
const check = process.argv.includes("--check");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const sha = async (file) => createHash("sha256").update(await readFile(file)).digest("hex").slice(0, 12);

async function pngs(dir) {
  const found = new Set();
  async function walk(current) {
    let entries = [];
    try { entries = await readdir(current, { withFileTypes: true }); } catch (error) { if (error.code !== "ENOENT") throw error; return; }
    for (const entry of entries) {
      const full = resolve(current, entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (entry.name.endsWith(".png")) found.add(relative(dir, full));
    }
  }
  await walk(dir);
  return found;
}

const webFiles = await pngs(webAssets);
const nativeFiles = await pngs(nativeAssets);
const manifestByPath = new Map();
for (const [key, url] of Object.entries(manifest)) {
  if (typeof url !== "string" || !url.startsWith("/game/assets/") || !url.endsWith(".png")) continue;
  manifestByPath.set(url.slice("/game/assets/".length), key);
}

const entries = [];
const paths = [...new Set([...webFiles, ...nativeFiles, ...manifestByPath.keys()])].sort();
for (const path of paths) {
  const key = manifestByPath.get(path) ?? path;
  const web = resolve(webAssets, path);
  const native = resolve(nativeAssets, path);
  const hasWeb = webFiles.has(path);
  const hasNative = nativeFiles.has(path);
  if (!hasWeb) {
    entries.push({ key, path, state: hasNative ? "native-only" : "manifest-missing-source" });
    continue;
  }
  if (!hasNative) {
    // New art can affect composition and is intentionally never copied without an explicit reviewed allow-list.
    entries.push({ key, path, state: "missing" });
    continue;
  }
  try { await stat(web); await stat(native); } catch { entries.push({ key, path, state: "manifest-missing-source" }); continue; }
  entries.push({ key, path, state: (await sha(web)) === (await sha(native)) ? "identical" : "different" });
}

const grouped = (state) => entries.filter((entry) => entry.state === state);
const section = (title, items) => `## ${title} (${items.length})\n\n${items.length ? items.map(({ key, path }) => `- \`${key}\` — \`${path}\``).join("\n") : "None."}\n`;
const heldBack = grouped("different").length + grouped("missing").length;
const report = `# Native asset sync triage

Generated by \`scripts/sync-native-assets.mjs\` from \`web/public/game/assets\` and \`web/public/game/assets/manifest.json\`. This report is a review list only. It does not overwrite native art and it does not copy missing art.

${heldBack} paths are byte-different or present only on the web. Those are the files a bulk copy would overwrite or add. Leave them until a reviewed allow-list exists.

- **Keep candidates** have the same relative path and a different SHA-256 prefix. Preserve the native composition.
- **Do not copy yet** means the PNG exists under web assets and is absent from the native Art bundle.
- **Native only** files stay where they are. The web tree is not a reason to delete them.
- **Synced** files already have byte-identical content.

${section("Synced", grouped("identical"))}
${section("Keep candidates: existing native art differs", grouped("different"))}
${section("Do not copy yet: present on web, absent from native Art", grouped("missing"))}
${section("Native only: leave in place", grouped("native-only"))}
${section("Manifest paths missing a web source", grouped("manifest-missing-source"))}`;

let current = "";
try { current = await readFile(reportPath, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
if (current !== report) {
  if (check) {
    console.error(`Out of sync: ${reportPath}`);
    process.exitCode = 1;
  } else {
    await mkdir(dirname(reportPath), { recursive: true });
    await writeFile(reportPath, report);
    console.log(`Updated ${relative(root, reportPath)}`);
    console.log(`Held back ${heldBack} paths (different ${grouped("different").length}, web-only ${grouped("missing").length}). No PNGs written.`);
  }
}
